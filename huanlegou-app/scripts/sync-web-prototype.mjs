#!/usr/bin/env node
/**
 * Copy huanlegou-prototype into huanlegou-app/web and generate src/webAssets.ts
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const srcRoot = path.resolve(root, '../huanlegou-prototype');
const webRoot = path.join(root, 'web');
const outFile = path.join(root, 'src/webAssets.ts');

const WEB_EXTENSIONS = new Set([
  '.html',
  '.css',
  '.js',
  '.jpg',
  '.jpeg',
  '.png',
  '.gif',
  '.webp',
  '.svg',
  '.ico',
  '.woff',
  '.woff2',
]);

function shouldIncludeWebFile(name) {
  if (name.startsWith('.')) return false;
  return WEB_EXTENSIONS.has(path.extname(name).toLowerCase());
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const src = path.join(from, entry.name);
    const dest = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dest);
    else if (shouldIncludeWebFile(entry.name)) fs.copyFileSync(src, dest);
  }
}

function walkFiles(dir, base = dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(full, base));
    else if (shouldIncludeWebFile(entry.name)) {
      files.push(path.relative(base, full).split(path.sep).join('/'));
    }
  }
  return files.sort();
}

if (!fs.existsSync(srcRoot)) {
  if (fs.existsSync(webRoot) && fs.existsSync(path.join(webRoot, 'index.html'))) {
    console.warn('Prototype not found at', srcRoot, '— reusing committed web/');
  } else {
    console.error('Missing prototype at', srcRoot, 'and no web/ bundle');
    process.exit(1);
  }
} else {
  if (fs.existsSync(webRoot)) fs.rmSync(webRoot, { recursive: true, force: true });
  copyDir(srcRoot, webRoot);
  console.log('Copied prototype → web/');
}

if (!fs.existsSync(webRoot)) {
  console.error('web/ folder missing');
  process.exit(1);
}

const files = walkFiles(webRoot);
const lines = files.map(
  (f) => `  '${f}': require('../web/${f}'),`,
);

const content = `// AUTO-GENERATED by scripts/sync-web-prototype.mjs — do not edit
/* eslint-disable @typescript-eslint/no-require-imports */
export const WEB_ASSETS: Record<string, number> = {
${lines.join('\n')}
};
export const WEB_FILE_COUNT = ${files.length};
`;

fs.writeFileSync(outFile, content);
console.log(`Synced ${files.length} web files → web/ and src/webAssets.ts`);
